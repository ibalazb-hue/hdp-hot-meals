export type CopyKey = keyof typeof en
export type Locale = 'en' | 'ar'

const LocaleContext = createContext<{ locale: Locale; setLocale: (locale: Locale) => void; t: (key: CopyKey) => string }>({
  locale: 'en',
  setLocale: () => undefined,
  t: (key) => en[key],
})

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => (localStorage.getItem('hdp-locale') === 'ar' ? 'ar' : 'en'))
  const setLocale = (next: Locale) => {
    localStorage.setItem('hdp-locale', next)
    setLocaleState(next)
  }
  useEffect(() => {
    document.documentElement.lang = locale
    document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr'
  }, [locale])
  const value = useMemo(() => ({ locale, setLocale, t: (key: CopyKey) => (locale === 'ar' ? ar[key] : en[key]) }), [locale])
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useI18n() {
  return useContext(LocaleContext)
}
